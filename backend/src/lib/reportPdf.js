// reportPdf.js — F11 PDF export. buildReportDocDefinition is pure (it only
// builds the pdfmake document object, so tests can inspect it); renderPdf is
// the only function that touches pdfmake.
//
// Fonts: pdfmake's built-in Helvetica (a standard PDF font), so nothing has to
// be bundled into the Cloud Run image. Standard fonts have no peso sign (₱),
// so amounts print as "PHP 12,345.00".

const PdfPrinter = require("pdfmake");

const FONTS = {
  Helvetica: {
    normal: "Helvetica",
    bold: "Helvetica-Bold",
    italics: "Helvetica-Oblique",
    bolditalics: "Helvetica-BoldOblique",
  },
};

// 12345.5 -> "PHP 12,345.50", -7500 -> "-PHP 7,500.00". No locale needed.
function formatPhp(value) {
  const cents = Math.round(Number(value) * 100) + 0;
  const sign = cents < 0 ? "-" : "";
  const abs = Math.abs(cents);
  const pesos = String(Math.floor(abs / 100)).replace(/\B(?=(\d{3})+(?!\d))/g, ",");
  return `${sign}PHP ${pesos}.${String(abs % 100).padStart(2, "0")}`;
}

const formatPct = (value) => (value === null || value === undefined ? "n/a" : `${value.toFixed(2)}%`);

// Manila wall-clock for people; the exact UTC instant is what gets hashed.
function formatGeneratedAt(iso) {
  const manila = new Date(new Date(iso).getTime() + 8 * 60 * 60 * 1000);
  return `${manila.toISOString().slice(0, 16).replace("T", " ")} (Asia/Manila), UTC ${iso}`;
}

const header = (text, alignment = "left") => ({ text, alignment, bold: true, fontSize: 9, fillColor: "#eeeeee" });
const right = (text, extra = {}) => ({ text, alignment: "right", ...extra });

/**
 * summary:  the object from buildSummary()
 * options:  { reportId, payloadHash, anchor, chartImage, generatedByName }
 *            anchor is { status: "Pending" | "Confirmed", txHash?, blockNumber? }
 */
function buildReportDocDefinition(summary, options) {
  const { reportId, payloadHash, anchor, chartImage, generatedByName } = options;
  const names = summary.projects.map((p) => p.name).join(", ");

  const single = summary.projects.length === 1;
  const t = summary.totals;

  // Amounts never wrap ("PHP" and the number stay on one line).
  const money = (value, extra = {}) => right(formatPhp(value), { noWrap: true, ...extra });
  const statusCell = (over, extra = {}) => ({ text: over ? "OVER BUDGET" : "Within budget", color: over ? "#b00020" : "#1b5e20", fontSize: 8, ...extra });

  // "Used" is measured to date (all approved spend up to the end date), the same
  // figure the chart and the Reports page show.
  const projectRows = summary.projects.map((p) => [
    p.name,
    money(p.budget),
    money(p.periodSpend),
    money(p.cumulativeSpend),
    money(p.netPnL, p.netPnL < 0 ? { color: "#b00020" } : {}),
    right(formatPct(p.cumulativeUtilizationPct), { noWrap: true }),
    statusCell(p.overrun),
  ]);
  // One project: the Total row would only repeat the project's own row.
  const totalRows = single
    ? []
    : [
        [
          { text: "Total", bold: true },
          money(t.budget, { bold: true }),
          money(t.periodSpend, { bold: true }),
          money(t.cumulativeSpend, { bold: true }),
          money(t.netPnL, { bold: true, ...(t.netPnL < 0 ? { color: "#b00020" } : {}) }),
          right(formatPct(t.cumulativeUtilizationPct), { bold: true, noWrap: true }),
          statusCell(t.overrun, { bold: true }),
        ],
      ];

  const birRows = summary.projects.map((p) => [p.name, right(formatPhp(p.birDeductibleSpend))]);

  // Cost variance to date = spend to date minus budget. Negative is under
  // budget; positive (red) is over.
  const varianceCell = (value, extra = {}) => money(value, { ...(value > 0 ? { color: "#b00020" } : {}), ...extra });
  const varianceRows = summary.projects.map((p) => [
    p.name,
    money(p.budget),
    money(p.cumulativeSpend),
    varianceCell(p.varianceToDate),
    right(formatPct(p.varianceToDatePct), { noWrap: true }),
  ]);

  const content = [
    { text: "Brick x Brick - Financial Report", fontSize: 18, bold: true, margin: [0, 0, 0, 6] },
    { text: `${single ? "Project" : "Projects"}: ${names}`, fontSize: 10 },
    { text: `Period: ${summary.period.from} to ${summary.period.to}`, fontSize: 10 },
    { text: `Generated: ${formatGeneratedAt(summary.generatedAt)}`, fontSize: 10 },
    ...(generatedByName ? [{ text: `Generated by: ${generatedByName}`, fontSize: 10 }] : []),
    { text: single ? "Budget and spend" : "Budget and spend by project", style: "section" },
    {
      table: {
        headerRows: 1,
        widths: ["*", "auto", "auto", "auto", "auto", "auto", "auto"],
        body: [
          [
            header("Project"),
            header("Budget", "right"),
            header("Spend (period)", "right"),
            header("Spend to date", "right"),
            header("Budget left", "right"),
            header("Used to date", "right"),
            header("Status"),
          ],
          ...projectRows,
          ...totalRows,
        ],
      },
      layout: "lightHorizontalLines",
      fontSize: 8,
    },
    { text: "Budget left = budget minus this period's spend. Used to date = all approved spend up to the end date, as a share of the budget.", fontSize: 7, color: "#555555", margin: [0, 4, 0, 0] },
    { text: "Cost variance (spend to date minus budget)", style: "section" },
    single
      ? {
          text: [
            { text: formatPhp(summary.projects[0].varianceToDate), bold: true },
            ` (${formatPct(summary.projects[0].varianceToDatePct)} of the budget): ${summary.projects[0].varianceToDate > 0 ? "over" : "under"} budget, counting all approved spend up to ${summary.period.to}.`,
          ],
          fontSize: 9,
        }
      : {
          table: {
            headerRows: 1,
            widths: ["*", "auto", "auto", "auto", "auto"],
            body: [
              [header("Project"), header("Budget", "right"), header("Spend to date", "right"), header("Cost variance", "right"), header("% of budget", "right")],
              ...varianceRows,
              [
                { text: "Total", bold: true },
                money(t.budget, { bold: true }),
                money(t.cumulativeSpend, { bold: true }),
                varianceCell(t.varianceToDate, { bold: true }),
                right(formatPct(t.varianceToDatePct), { bold: true, noWrap: true }),
              ],
            ],
          },
          layout: "lightHorizontalLines",
          fontSize: 8,
        },
    { text: "Negative = under budget, positive = over budget.", fontSize: 7, color: "#555555", margin: [0, 4, 0, 0] },
    { text: "Budget used to date", style: "section" },
    { image: chartImage, width: 480 },
    { text: "BIR tax-deductible spend (Formal receipts only)", style: "section" },
    single
      ? {
          text: [
            { text: formatPhp(summary.projects[0].birDeductibleSpend), bold: true },
            ` of this period's spend is tax-deductible (receipts classed Formal-Tax-Deductible).`,
          ],
          fontSize: 9,
        }
      : {
          table: {
            headerRows: 1,
            widths: ["*", "auto"],
            body: [
              [header("Project"), header("Formal-Tax-Deductible", "right")],
              ...birRows,
              [{ text: "Total", bold: true }, right(formatPhp(t.birDeductibleSpend), { bold: true })],
            ],
          },
          layout: "lightHorizontalLines",
          fontSize: 9,
        },
  ];

  const w = summary.warnings;
  if (w.pendingExpenses > 0 || w.fraudFlaggedExpenses > 0) {
    content.push(
      { text: "Integrity warnings", style: "section", color: "#b00020" },
      {
        ul: [
          ...(w.pendingExpenses > 0
            ? [`${w.pendingExpenses} expense(s) in this period are still Pending approval and are not included in the figures.`]
            : []),
          ...(w.fraudFlaggedExpenses > 0
            ? [`${w.fraudFlaggedExpenses} expense(s) in this period carry an unresolved fraud flag.`]
            : []),
        ],
        fontSize: 9,
      }
    );
  }

  return {
    pageSize: "A4",
    pageMargins: [40, 40, 40, 60],
    defaultStyle: { font: "Helvetica", fontSize: 10 },
    styles: { section: { fontSize: 12, bold: true, margin: [0, 14, 0, 6] } },
    content,
    footer: (page, pages) => ({
      margin: [40, 10, 40, 0],
      fontSize: 7,
      color: "#555555",
      stack: [
        { text: `Report ID: ${reportId}` },
        { text: `Report hash (SHA-256): ${payloadHash}` },
        {
          text:
            anchor.status === "Confirmed"
              ? `Blockchain anchor: Confirmed (tx ${anchor.txHash}, block ${anchor.blockNumber})`
              : "Blockchain anchor: Pending (the network was unavailable; it will be secured on retry)",
        },
        { text: `Page ${page} of ${pages}`, alignment: "right" },
      ],
    }),
  };
}

// Document definition -> Buffer.
function renderPdf(docDefinition) {
  return new Promise((resolve, reject) => {
    const doc = new PdfPrinter(FONTS).createPdfKitDocument(docDefinition);
    const chunks = [];
    doc.on("data", (chunk) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);
    doc.end();
  });
}

module.exports = { buildReportDocDefinition, renderPdf, formatPhp, formatPct, formatGeneratedAt };
